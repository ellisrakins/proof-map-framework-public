def _regime(
    description: str,
    *,
    dimensions: dict[str, object] | None = None,
    assumptions: list[str] | None = None,
) -> list[ValidityRegime]:
    return [
        ValidityRegime(
            id="primary",
            description=description,
            dimensions=dimensions or {},
            assumptions=assumptions or [],
        )
    ]


def _profile(
    *,
    id: str,
    name: str,
    kind: TheoryKind,
    maturity: TheoryMaturity,
    evidence: EvidenceStatus,
    family: str,
    summary: str,
    domains: list[str],
    foundations: list[str],
    mathematics: list[str],
    regime: str,
    sources: list[str],
    results: list[str] | None = None,
    questions: list[str] | None = None,
    tests: list[str] | None = None,
    dimensions: dict[str, object] | None = None,
    tags: list[str] | None = None,
) -> TheoryProfile:
    return TheoryProfile(
        id=id,
        name=name,
        kind=kind,
        maturity=maturity,
        evidence_status=evidence,
        family=family,
        summary=summary,
        domains=domains,
        foundations=foundations,
        mathematical_frameworks=mathematics,
        validity_regimes=_regime(regime, dimensions=dimensions),
        key_results=results or [],
        open_questions=questions or [],
        discriminating_tests=tests or [],
        source_ids=sources,
        last_verified=VERIFIED_DATE,
        tags=tags or [],
    )


